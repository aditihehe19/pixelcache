#!/usr/bin/env python3
"""Document which traversal loops the compiler auto-vectorised.

Re-runs the exact compile commands from build/compile_commands.json for the
traversal translation units of both build variants with GCC's
-fopt-info-vec-optimized (and -missed for the summary), and writes
results/vectorization_report.md. This makes the "scalar vs SIMD" difference
between the two benchmark binaries explicit instead of assumed.

Usage: python scripts/vectorization_report.py [--build build]
"""
import argparse
import collections
import json
import os
import re
import shlex
import subprocess

UNITS = ["traversal_row_major.cpp", "traversal_tiled.cpp", "traversal_morton.cpp"]


def source_line(path, line):
    try:
        with open(path, encoding="utf-8") as f:
            return f.readlines()[line - 1].strip()
    except (OSError, IndexError):
        return ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", default="build")
    ap.add_argument("--out", default=os.path.join("results", "vectorization_report.md"))
    args = ap.parse_args()
    with open(os.path.join(args.build, "compile_commands.json"), encoding="utf-8") as f:
        db = json.load(f)

    md = ["# Auto-vectorisation report", "",
          "Generated by `scripts/vectorization_report.py` from the real compile commands "
          "(`-fopt-info-vec-optimized`). Each row is a loop GCC vectorised; template loops appear once per "
          "kernel/mapping instantiation.", ""]
    for variant in ("native", "scalar"):
        md += [f"## Variant `{variant}`", ""]
        for entry in db:
            src = entry["file"].replace("\\", "/")
            if f"cachevision_core_{variant}" not in entry.get("output", entry["command"]) or \
                    not any(src.endswith(u) for u in UNITS):
                continue
            # Re-use the exact command line (its quoting is what CMake intended),
            # only redirecting the object file and adding the report flag.
            cmd = re.sub(r" -o \S+", " -o " + os.devnull, entry["command"], count=1) + " -fopt-info-vec-optimized"
            if os.name != "nt":
                cmd = shlex.split(cmd)
            res = subprocess.run(cmd, cwd=entry["directory"], capture_output=True, text=True)
            if res.returncode != 0:
                raise SystemExit(f"compile failed for {src}: {res.stderr[:2000]}")
            hits = collections.Counter()
            for line in res.stderr.splitlines():
                m = re.search(r"([^\s:]+(?::[\\/][^:]+)?):(\d+):\d+: optimized: (loop vectorized using (\d+) byte vectors|basic block part vectorized.*|loop vectorized.*)", line)
                if m:
                    path, ln, what = m.group(1), int(m.group(2)), m.group(3)
                    hits[(os.path.basename(path), ln, what.split(" using ")[-1] if "using" in what else what, path)] += 1
            md.append(f"### `{os.path.basename(src)}`")
            md.append("")
            if not hits:
                md += ["No loops vectorised.", ""]
                continue
            md += ["| location | vectorisation | instantiations | source |", "|---|---|---|---|"]
            for (base, ln, what, path), n in sorted(hits.items(), key=lambda kv: (kv[0][0], kv[0][1])):
                code = source_line(path if os.path.isabs(path) else os.path.join(entry["directory"], path), ln)
                md.append(f"| {base}:{ln} | {what} | {n} | `{code[:70]}` |")
            md.append("")
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
